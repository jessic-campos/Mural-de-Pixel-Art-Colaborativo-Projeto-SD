public class Pixel {

    private int x;
    private int y;
    private String cor;

    public Pixel(int x, int y, String cor) {
        this.x = x;
        this.y = y;
        this.cor = cor;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }

    public String getCor() {
        return cor;
    }
}